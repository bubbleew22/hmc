import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../../data/db/app_database.dart';
import '../config/app_config.dart';
import '../utils/money.dart';
import '../utils/time.dart';

/// Professional invoice/receipt PDF built from stored transaction data.
class InvoicePdf {
  static Future<Uint8List> build({
    required ShopSetting settings,
    required SalesInvoice invoice,
    required List<SalesItem> items,
    required List<_ItemLabel> labels,
    required Customer customer,
  }) async {
    final doc = pw.Document();
    final format = settings.invoiceFormat;
    final pageFormat =
        format == 'thermal' ? const PdfPageFormat(72 * PdfPageFormat.mm, double.infinity) : PdfPageFormat.a4;

    doc.addPage(
      pw.Page(
        pageFormat: pageFormat,
        margin: const pw.EdgeInsets.all(24),
        build: (ctx) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            _header(settings),
            pw.SizedBox(height: 16),
            _meta(invoice, customer),
            pw.SizedBox(height: 12),
            _itemsTable(items, labels),
            pw.SizedBox(height: 12),
            _totals(invoice),
            if (invoice.warranty.trim().isNotEmpty) ...[
              pw.SizedBox(height: 12),
              pw.Text('Warranty: ${invoice.warranty}',
                  style: const pw.TextStyle(fontSize: 10)),
            ],
            if (invoice.notes.trim().isNotEmpty) ...[
              pw.SizedBox(height: 8),
              pw.Text('Notes: ${invoice.notes}',
                  style: const pw.TextStyle(fontSize: 10)),
            ],
            pw.Spacer(),
            if (settings.invoiceFooter.trim().isNotEmpty)
              pw.Center(
                child: pw.Text(settings.invoiceFooter,
                    style: const pw.TextStyle(fontSize: 10),
                    textAlign: pw.TextAlign.center),
              ),
            pw.SizedBox(height: 8),
            pw.Center(
              child: pw.Text(
                'Generated by ${AppConfig.appName} — ${AppConfig.appSubtitle}',
                style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600),
              ),
            ),
          ],
        ),
      ),
    );
    return doc.save();
  }

  static pw.Widget _header(ShopSetting s) => pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Text(s.shopName,
                  style: pw.TextStyle(
                      fontSize: 22,
                      fontWeight: pw.FontWeight.bold,
                      color: PdfColor.fromHex('#0B1B33'))),
              pw.Text(s.subtitle,
                  style: pw.TextStyle(
                      fontSize: 13,
                      fontWeight: pw.FontWeight.bold,
                      color: PdfColor.fromHex('#B8860B'))),
              if (s.contactNumber.trim().isNotEmpty)
                pw.Text('Contact: ${s.contactNumber}',
                    style: const pw.TextStyle(fontSize: 10)),
              if (s.address.trim().isNotEmpty)
                pw.Text(s.address, style: const pw.TextStyle(fontSize: 10)),
            ],
          ),
          pw.Container(
            padding: const pw.EdgeInsets.symmetric(horizontal: 14, vertical: 8),
            decoration: pw.BoxDecoration(
              color: PdfColor.fromHex('#0B1B33'),
              borderRadius: pw.BorderRadius.circular(8),
            ),
            child: pw.Text('INVOICE',
                style: pw.TextStyle(
                    fontSize: 16,
                    fontWeight: pw.FontWeight.bold,
                    color: PdfColors.white)),
          ),
        ],
      );

  static pw.Widget _meta(SalesInvoice inv, Customer c) => pw.Container(
        padding: const pw.EdgeInsets.all(10),
        decoration: pw.BoxDecoration(
          border: pw.Border.all(color: PdfColors.grey300),
          borderRadius: pw.BorderRadius.circular(8),
        ),
        child: pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text('Invoice: ${inv.invoiceNo}',
                    style: pw.TextStyle(
                        fontSize: 12, fontWeight: pw.FontWeight.bold)),
                pw.Text('Date: ${PkTime.formatDateTime(inv.saleDate)}',
                    style: const pw.TextStyle(fontSize: 10)),
                pw.Text('Payment: ${_prettyPayment(inv)}',
                    style: const pw.TextStyle(fontSize: 10)),
              ],
            ),
            pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.end,
              children: [
                pw.Text('Customer: ${c.name}',
                    style: pw.TextStyle(
                        fontSize: 12, fontWeight: pw.FontWeight.bold)),
                if (c.phone.trim().isNotEmpty)
                  pw.Text(c.phone, style: const pw.TextStyle(fontSize: 10)),
              ],
            ),
          ],
        ),
      );

  static String _prettyPayment(SalesInvoice inv) {
    final type = switch (inv.paymentType) {
      'full' => 'Full Payment',
      'partial' => 'Partial Payment',
      _ => 'Credit / Udhaar',
    };
    return '$type (${inv.paymentMethod})';
  }

  static pw.Widget _itemsTable(
      List<SalesItem> items, List<_ItemLabel> labels) {
    final rows = <List<String>>[];
    for (var i = 0; i < items.length; i++) {
      final it = items[i];
      rows.add([
        '${i + 1}',
        labels[i].title,
        labels[i].imei.isEmpty ? '-' : labels[i].imei,
        '${it.quantity}',
        Money.format(it.unitPrice, withSymbol: false),
        Money.format(it.unitPrice * it.quantity, withSymbol: false),
      ]);
    }
    return pw.TableHelper.fromTextArray(
      headers: ['#', 'Item', 'IMEI/Serial', 'Qty', 'Unit Price', 'Total'],
      data: rows,
      headerStyle:
          pw.TextStyle(fontWeight: pw.FontWeight.bold, color: PdfColors.white),
      headerDecoration:
          pw.BoxDecoration(color: PdfColor.fromHex('#0B1B33')),
      cellStyle: const pw.TextStyle(fontSize: 10),
      headerAlignments: const {},
    );
  }

  static pw.Widget _totals(SalesInvoice inv) => pw.Align(
        alignment: pw.Alignment.centerRight,
        child: pw.Container(
          width: 240,
          child: pw.Column(
            children: [
              _row('Subtotal', Money.format(inv.subtotal)),
              if (inv.discount > 0)
                _row('Discount', '- ${Money.format(inv.discount)}'),
              if (inv.tax > 0) _row('Tax', Money.format(inv.tax)),
              pw.Divider(),
              _row('Total', Money.format(inv.total), bold: true),
              _row('Paid', Money.format(inv.paid)),
              _row('Balance Due', Money.format(inv.total - inv.paid),
                  bold: true,
                  color: (inv.total - inv.paid) > 0
                      ? PdfColor.fromHex('#B91C1C')
                      : PdfColor.fromHex('#15803D')),
            ],
          ),
        ),
      );

  static pw.Widget _row(String label, String value,
          {bool bold = false, PdfColor? color}) =>
      pw.Padding(
        padding: const pw.EdgeInsets.symmetric(vertical: 2),
        child: pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Text(label,
                style: pw.TextStyle(
                    fontWeight:
                        bold ? pw.FontWeight.bold : pw.FontWeight.normal,
                    fontSize: 11)),
            pw.Text(value,
                style: pw.TextStyle(
                    fontWeight:
                        bold ? pw.FontWeight.bold : pw.FontWeight.normal,
                    fontSize: 11,
                    color: color ?? PdfColors.black)),
          ],
        ),
      );
}

/// Display label for one invoice line (resolved by the caller from catalogue).
class ItemLabel {
  final String title;
  final String imei;
  const ItemLabel({required this.title, this.imei = ''});
}

typedef _ItemLabel = ItemLabel;

/// Customer statement / ledger PDF.
Future<Uint8List> buildLedgerPdf(
    Customer customer, List<dynamic> entries) async {
  final doc = pw.Document();
  doc.addPage(
    pw.Page(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(24),
      build: (ctx) => pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text('Customer Statement',
              style: pw.TextStyle(
                  fontSize: 20, fontWeight: pw.FontWeight.bold)),
          pw.SizedBox(height: 4),
          pw.Text(customer.name,
              style: const pw.TextStyle(fontSize: 14)),
          if (customer.phone.trim().isNotEmpty)
            pw.Text(customer.phone,
                style: const pw.TextStyle(fontSize: 11)),
          pw.SizedBox(height: 12),
          pw.TableHelper.fromTextArray(
            headers: const [
              'Date',
              'Reference',
              'Description',
              'Debit',
              'Credit',
              'Balance'
            ],
            data: [
              for (final e in entries)
                [
                  PkTime.formatDate(e.date as int),
                  e.reference as String,
                  (e.description as String).length > 28
                      ? '${(e.description as String).substring(0, 28)}…'
                      : e.description as String,
                  (e.debit as int) == 0
                      ? '-'
                      : Money.format(e.debit as int,
                          withSymbol: false),
                  (e.credit as int) == 0
                      ? '-'
                      : Money.format(e.credit as int,
                          withSymbol: false),
                  Money.format(e.runningBalance as int,
                      withSymbol: false),
                ],
            ],
            headerStyle: pw.TextStyle(
                fontWeight: pw.FontWeight.bold,
                color: PdfColors.white),
            headerDecoration:
                pw.BoxDecoration(color: PdfColor.fromHex('#0B1B33')),
            cellStyle: const pw.TextStyle(fontSize: 9),
          ),
        ],
      ),
    ),
  );
  return doc.save();
}
